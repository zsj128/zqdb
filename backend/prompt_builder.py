# -*- coding: utf-8 -*-
"""
Prompt 构建模块：从 main.py 拆出。

包含：
  - build_legal_prompt  统一法律问答 Prompt（结论+分析+引用，支持附件上下文）
  - format_for_llm      把检索结果格式化为模型可读的参考资料文本
"""


def build_legal_prompt(query, context, attachment_text="", attachment_name=""):
    """统一 Prompt：结论在前 + 分析在后。

    可选附件（attachment_text）作为用户上传文件的上下文附加到参考资料中。
    """
    # 结论要求
    conclusion_rule = (
        """- 如果是法律案例分析之类的：简洁准确，无需冗长推理\n- 案例类需包含：案例名称、基本案情、裁判要点、裁判结果
       - 如果是法律问题解答：先说结论，明确回答用户问题\n- 分点列出关键要点，清晰易读"""
    )
    # 分析要求
    analysis_rule = (
        """- 如果是法律案例分析之类的：仅在需要展示推理依据时使用此段落\n- 列出引用的法条和逻辑推导过程
       - 如果是法律问题解答：识别涉及的法律关系\n- 逐条引用相关法条并分析\n- 说明推理逻辑和判断依据"""
    )
    # 注意事项
    notes = (
        """【注意事项】
    - 如果参考资料中没有完全匹配的内容，请在结论中说明"现有资料未涵盖此方面"
    - 不要编造法条内容，仅基于给定资料作答
    - 回答要专业、准确、有法律依据
    - 如果用户上传了文件，请优先结合【用户上传的文件】中的内容进行分析
    """)
    # 附件内容块（用户上传的文件作为对话上下文）
    attachment_block = ""
    if attachment_text:
        attachment_block = f"""
    【用户上传的文件：{attachment_name}】
    以下是用户上传文件中的内容，请结合其中的事实与数据回答用户问题：
    {attachment_text}
    """
    return f"""你是一个专业的法律咨询助手。请基于以下参考资料回答用户问题。

    【回答范围 —— 最高优先级，必须首先判断】
    你只回答与法律相关的问题。如果用户的问题属于以下任一类非法律问题，
    请直接回复以下固定话术，不要展开回答，也不要尝试回答该问题：
    "抱歉，我是专业的法律咨询助手，只能回答法律相关的问题。您的问题与法律无关，我无法为您解答。"
    非法律问题包括但不限于：
    - 闲聊、寒暄、情感倾诉（如"你好吗""今天天气如何"）
    - 编程、代码、技术问题
    - 数学计算、物理化学等学科问题
    - 翻译、写作、改写等通用任务
    - 医疗诊断、投资建议等其他专业领域
    只有在问题确实涉及法律（法律关系、权利义务、法律后果、诉讼、合同、犯罪、纠纷等）时，才继续按下方格式回答。

    【输出格式 — 严格遵守】
    你的回答必须严格分为两部分，且使用以下固定标题（不要使用 markdown 的 # 号标题，
    不要写成"## 第一部分""## 第二部分"，请直接使用下述文字作为段落标题）：

    第一部分：直接给出答案（结论）
    {conclusion_rule}

    第二部分：【法律分析】
    {analysis_rule}

    【引用格式】
    法条引用必须标注：【引用：《XX法》第X条】
    案例引用必须标注：【引用：指导案例X号】

    【法律问题解答时】
    {notes}

    {attachment_block}

    【参考资料】
    {context}

    【用户问题】
    {query}

    请严格按照上述格式输出："""


def format_for_llm(results):
    """把检索结果（list[dict]）格式化为模型参考资料的纯文本。"""
    parts = []
    for i, item in enumerate(results, 1):
        arts = f"【条文: {item.get('articles', '')}】" if item.get('articles') else ""
        parts.append(f"[{i}] {arts}\n{item['text']}")
    return "\n\n".join(parts)
